#!/usr/bin/env python3
"""Generate the lookup tables of the 2x2x2 Rubik's Cube solver.

Run from the repository root (stdlib only, deterministic, about a second):

    python3 mytools/rubik_tables.py

It writes the same data twice:

    src/rubik/rubik_tables.h   C header (static const arrays) for rubik.c
    src/rubik/rubik_tables.S   GNU as data (global labels) for rubik.S

Cube model (tests/trubik.c): p[i] is the cubie at position i, o[i] its twist.
A quarter turn of face f (0=R, 1=B, 2=D) sets n.p[i] = c.p[source[f][i]] and
n.o[i] = (c.o[source[f][i]] + twist[f][i]) % 3.

Joint coordinate of group g (A: cubies 0,1,2; B: cubies 3,4,5): x[k] is the
position of cubie 3g+k and oo[k] the twist there;
    second = x1 - (x1 > x0), third = x2 - (x2 > x0) - (x2 > x1),
    rank = (x0 * 6 + second) * 5 + third              (0..209)
    joint = rank * 27 + (oo0 * 3 + oo1) * 3 + oo2      (0..5669)
The solved cube has A = 0 and B = 2916. One transition table serves both.

Tables:
    joint_next[3][5670]  u16  joint after one quarter turn of face f
    pdb[2][5670]         u8   BFS distance (9 moves) to A = 0 / to B = 2916
    near_start[5671]     u16  entries of A = a: near_entry[start[a]..start[a+1])
    near_entry[12224]    u16  (B << 3) | distance, ascending B within each A;
                              every state at distance <= 5, keyed by (A, B)
"""

import os
import sys

SOURCE = ((1, 4, 2, 0, 3, 5, 6), (0, 1, 2, 4, 5, 6, 3), (0, 2, 5, 3, 1, 4, 6))
TWIST = ((1, 2, 0, 2, 1, 0, 0), (0, 0, 0, 1, 2, 1, 2), (0, 0, 0, 0, 0, 0, 0))
JOINT = 5670
GOAL_B = 2916
NEAR_DEPTH = 5


def turn(p, o, f):
    s, t = SOURCE[f], TWIST[f]
    return (tuple(p[s[i]] for i in range(7)),
            tuple((o[s[i]] + t[i]) % 3 for i in range(7)))


def encode(x, oo):
    x0, x1, x2 = x
    second = x1 - (x1 > x0)
    third = x2 - (x2 > x0) - (x2 > x1)
    rank = (x0 * 6 + second) * 5 + third
    return rank * 27 + (oo[0] * 3 + oo[1]) * 3 + oo[2]


def decode(j):
    rank, ori = divmod(j, 27)
    oo = (ori // 9, ori // 3 % 3, ori % 3)
    rest, third = divmod(rank, 5)
    x0, second = divmod(rest, 6)
    free = [i for i in range(7) if i != x0]
    x1 = free[second]
    free.remove(x1)
    return (x0, x1, free[third]), oo


def coord(p, o, g):
    x, oo = [], []
    for k in range(3):
        i = p.index(3 * g + k)
        x.append(i)
        oo.append(o[i])
    return encode(x, oo)


def build_joint_next():
    # The cubie at position src moves to dst where SOURCE[f][dst] == src.
    table = []
    for f in range(3):
        dest = [SOURCE[f].index(src) for src in range(7)]
        row = []
        for j in range(JOINT):
            x, oo = decode(j)
            nx = [dest[xi] for xi in x]
            no = [(oo[k] + TWIST[f][nx[k]]) % 3 for k in range(3)]
            row.append(encode(nx, no))
        table.append(row)
    return table


def build_pdb(nxt, goal):
    dist = [255] * JOINT
    dist[goal] = 0
    frontier = [goal]
    d = 0
    while frontier:
        d += 1
        new = []
        for j in frontier:
            for f in range(3):
                c = j
                for _ in range(3):
                    c = nxt[f][c]
                    if dist[c] == 255:
                        dist[c] = d
                        new.append(c)
        frontier = new
    assert 255 not in dist
    return dist


def build_near():
    start = (tuple(range(7)), (0,) * 7)
    seen = {start: 0}
    frontier = [start]
    for d in range(1, NEAR_DEPTH + 1):
        new = []
        for p, o in frontier:
            for f in range(3):
                q, r = p, o
                for _ in range(3):
                    q, r = turn(q, r, f)
                    if (q, r) not in seen:
                        seen[(q, r)] = d
                        new.append((q, r))
        frontier = new
    by_key = {}
    for (p, o), d in seen.items():
        key = (coord(p, o, 0), coord(p, o, 1))
        assert key not in by_key, "(A, B) does not identify a state"
        by_key[key] = d
    keys = sorted(by_key)
    near_start = [0] * (JOINT + 1)
    for a, _ in keys:
        near_start[a + 1] += 1
    for a in range(JOINT):
        near_start[a + 1] += near_start[a]
    near_entry = [(b << 3) | by_key[(a, b)] for a, b in keys]
    return near_start, near_entry


DESCRIPTION = [
    "Lookup tables of the 2x2x2 Rubik's Cube solver.",
    "",
    "Generated by mytools/rubik_tables.py; do not edit by hand.",
    "",
    "A joint coordinate (0..5669) encodes the positions and twists of three",
    "cubies: group A tracks cubies 0, 1, 2 and group B cubies 3, 4, 5. With",
    "x[k] the position of the k-th cubie and oo[k] its twist,",
    "  second = x1 - (x1 > x0), third = x2 - (x2 > x0) - (x2 > x1),",
    "  joint = ((x0 * 6 + second) * 5 + third) * 27 + (oo0 * 3 + oo1) * 3 + oo2.",
    "The solved cube has A = 0 and B = 2916.",
    "",
    "joint_next[f][j]  joint after one quarter turn of face f (R, B, D)",
    "pdb[g][j]         distance to the goal of group g (A, B) over all nine",
    "                  moves; a lower bound on the distance of the cube",
    "near_start[a]     entries of A = a are near_entry[near_start[a]] up to",
    "                  near_entry[near_start[a + 1] - 1]",
    "near_entry[k]     (B << 3) | distance, ascending B within each A: every",
    "                  state at distance <= 5, keyed by (A, B)",
]


def c_array(decl, rows, per_line):
    out = [decl + " = {"]
    two_d = isinstance(rows[0], list)
    groups = rows if two_d else [rows]
    ind = "        " if two_d else "    "
    for g in groups:
        if two_d:
            out.append("    {")
        for i in range(0, len(g), per_line):
            out.append(ind + ", ".join(str(v) for v in g[i:i + per_line]) + ",")
        if two_d:
            out.append("    },")
    out.append("};")
    return out


def write_header(path, nxt, pdb, near_start, near_entry):
    lines = ["#pragma once", "", "#include <stdint.h>", "", "/* " + DESCRIPTION[0]]
    lines += [(" * " + s).rstrip() for s in DESCRIPTION[1:]]
    lines += [" */", ""]
    lines += ["#define RUBIK_JOINT %d" % JOINT,
              "#define RUBIK_GOAL_B %d" % GOAL_B,
              "#define RUBIK_NEAR %d" % len(near_entry),
              "#define RUBIK_NEAR_DEPTH %d" % NEAR_DEPTH, "",
              "/* clang-format off */"]
    lines += c_array("static const uint16_t rubik_joint_next[3][RUBIK_JOINT]",
                     nxt, 12)
    lines.append("")
    lines += c_array("static const uint8_t rubik_pdb[2][RUBIK_JOINT]", pdb, 24)
    lines.append("")
    lines += c_array("static const uint16_t rubik_near_start[RUBIK_JOINT + 1]",
                     near_start, 12)
    lines.append("")
    lines += c_array("static const uint16_t rubik_near_entry[RUBIK_NEAR]",
                     near_entry, 12)
    lines.append("/* clang-format on */")
    with open(path, "w") as fp:
        fp.write("\n".join(lines) + "\n")


def s_table(name, directive, values, per_line):
    out = ["", "    .balign 4", "    .globl %s" % name,
           "    .type %s, @object" % name, "%s:" % name]
    for i in range(0, len(values), per_line):
        out.append("    %s %s" % (directive,
                                  ", ".join(str(v) for v in values[i:i + per_line])))
    out.append("    .size %s, . - %s" % (name, name))
    return out


def write_asm(path, nxt, pdb, near_start, near_entry):
    lines = ["/* " + DESCRIPTION[0]]
    lines += [(" * " + s).rstrip() for s in DESCRIPTION[1:]]
    lines += [" *",
              " * Labels: rubik_asm_joint_next (.half, 3 x 5670, row f at 11340 * f),",
              " * rubik_asm_pdb (.byte, 2 x 5670, row B at 5670),",
              " * rubik_asm_near_start (.half, 5671), rubik_asm_near_entry (.half).",
              " */", "", "    .section .rodata"]
    lines += s_table("rubik_asm_joint_next", ".half", sum(nxt, []), 16)
    lines += s_table("rubik_asm_pdb", ".byte", sum(pdb, []), 16)
    lines += s_table("rubik_asm_near_start", ".half", near_start, 16)
    lines += s_table("rubik_asm_near_entry", ".half", near_entry, 16)
    with open(path, "w") as fp:
        fp.write("\n".join(lines) + "\n")


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    nxt = build_joint_next()
    pdb = [build_pdb(nxt, 0), build_pdb(nxt, GOAL_B)]
    near_start, near_entry = build_near()
    assert len(near_entry) == 12224 and near_start[JOINT] == 12224
    write_header(os.path.join(root, "src/rubik/rubik_tables.h"),
                 nxt, pdb, near_start, near_entry)
    write_asm(os.path.join(root, "src/rubik/rubik_tables.S"),
              nxt, pdb, near_start, near_entry)
    print("pdb max A=%d B=%d, near=%d" % (max(pdb[0]), max(pdb[1]),
                                          len(near_entry)), file=sys.stderr)


if __name__ == "__main__":
    main()
